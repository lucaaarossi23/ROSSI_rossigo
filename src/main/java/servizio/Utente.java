package modello;

public class Utente {
    private String ID;
    private String nome;
    private String email;
    private String codiceFiescale;
    private double credito;

    public String getID() {
        return ID;
    }

    public String getNome() {
        return nome;
    }

    public String getEmail() {
        return email;
    }

    public String getCodiceFiescale() {
        return codiceFiescale;
    }

    public double getCredito() {
        return credito;
    }
}
